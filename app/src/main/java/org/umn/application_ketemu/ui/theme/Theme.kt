    outlineVariant = DarkOutlineVariant
)

/**
 * Tema aplikasi Ketemu.
 *
 * Catatan penting: dynamic color (Material You) sengaja DIMATIKAN.
 * Alasannya, PRD menetapkan warna identitas Teal + Orange dari logo Ketemu
 * sebagai bagian dari identitas/kepercayaan produk, sehingga warna brand
 * tidak boleh berubah mengikuti wallpaper perangkat pengguna.
 *
 * @param darkTheme ikuti preferensi sistem secara default.
 */
@Composable
fun KetemuTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit
) {
    val colorScheme = if (darkTheme) KetemuDarkColorScheme else KetemuLightColorScheme

    MaterialTheme(
        colorScheme = colorScheme,
        typography = KetemuTypography,
        content = content
    )
}
